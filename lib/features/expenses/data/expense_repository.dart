import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../../app/providers.dart';
import '../../../core/errors/app_error.dart';
import '../../../data/firebase/firestore_paths.dart';
import '../../../data/firebase/firestore_streams.dart';
import '../../activity_feed/data/feed_repository.dart';
import '../../activity_feed/domain/feed_event.dart';
import '../../settlements/data/settlement_repository.dart';
import '../domain/balances.dart';
import '../domain/expense.dart';

class ExpenseRepository {
  ExpenseRepository(this._db, this._feed);

  final FirebaseFirestore _db;
  final FeedRepository _feed;

  /// One bounded listener feeds both the list and balance calculation. A
  /// tour beyond this size shows a notice (see [Snapshot.hasMore]).
  static const queryLimit = 1000;

  CollectionReference<Map<String, dynamic>> _col(String tourId) =>
      _db.collection(FirestorePaths.expenses(tourId));

  String newId(String tourId) => _col(tourId).doc().id;

  Stream<Snapshot<Expense>> watch(String tourId) => watchQuery(
    _col(tourId).orderBy('occurredAt', descending: true),
    (doc) => Expense.fromDoc(
      doc.id,
      doc.data(),
      hasPendingWrites: doc.metadata.hasPendingWrites,
    ),
    limit: queryLimit,
  );

  Map<String, dynamic> _fields(ExpenseDraft d) => {
    'title': d.title.trim(),
    'amountMinor': d.amountMinor,
    'currencyCode': d.currencyCode,
    'payerUid': d.payerUid,
    'shares': d.shares,
    'splitMethod': d.splitMethod.name,
    if (d.splitWeights.isNotEmpty) 'splitWeights': d.splitWeights,
    'category': d.category.name,
    'occurredAt': Timestamp.fromDate(d.occurredAt.toUtc()),
    'note': ?d.note,
  };

  /// New expenses may be recorded offline; they show as "Pending sync" to
  /// the author and are not counted for others until the server has them.
  /// [id] is generated by the form once, so a retry cannot duplicate.
  Future<WriteOutcome> add({
    required String tourId,
    required String id,
    required ExpenseDraft draft,
    required String uid,
  }) {
    final batch = _db.batch()
      ..set(_col(tourId).doc(id), {
        ..._fields(draft),
        'createdBy': uid,
        'createdAt': FieldValue.serverTimestamp(),
        'updatedAt': FieldValue.serverTimestamp(),
        'revisionCount': 0,
        'schemaVersion': Expense.schemaVersion,
      })
      ..set(
        _feed.newRef(tourId),
        _feed.eventData(
          type: FeedEventType.expenseAdded,
          actorUid: uid,
          refId: id,
          label: draft.title,
        ),
      );
    return commitQueued(batch.commit());
  }

  /// Edits run in a transaction (online only). If someone else changed the
  /// expense since the editor loaded it ([expectedRevision] differs), the
  /// edit is refused with a conflict instead of silently overwriting.
  Future<void> edit({
    required String tourId,
    required String expenseId,
    required ExpenseDraft draft,
    required int expectedRevision,
    required String uid,
    String? reason,
  }) async {
    final ref = _col(tourId).doc(expenseId);
    final changed = await _db
        .runTransaction((tx) async {
          final snap = await tx.get(ref);
          if (!snap.exists) throw const AppException(AppErrorKind.notFound);
          final current = Expense.fromDoc(snap.id, snap.data()!);
          if (current.isDeleted)
            throw const AppException(AppErrorKind.notFound);
          if (current.revisionCount != expectedRevision) {
            throw const AppException(AppErrorKind.conflict);
          }
          final before = current.editableFields();
          final after = draft.editableFields();
          final fields = diffFields(before, after);
          if (fields.isEmpty) return false;
          if (current.revisionCount + 1 > Revision.maxRevisions) {
            throw const AppException(AppErrorKind.quota, 'revisions');
          }
          final revision = current.revisionCount + 1;
          tx.set(ref, {
            ..._fields(draft),
            'createdBy': current.createdBy,
            'createdAt': snap.data()!['createdAt'],
            'updatedAt': FieldValue.serverTimestamp(),
            'updatedBy': uid,
            'revisionCount': revision,
            'schemaVersion': Expense.schemaVersion,
          });
          tx.set(ref.collection('revisions').doc('$revision'), {
            'editorUid': uid,
            'editedAt': FieldValue.serverTimestamp(),
            'changedFields': fields,
            'before': _compact(before, fields),
            'after': _compact(after, fields),
            if (reason != null && reason.trim().isNotEmpty)
              'reason': reason.trim(),
          });
          return true;
        })
        .timeout(const Duration(seconds: 20));
    if (changed) {
      await _feed.record(
        tourId,
        type: FeedEventType.expenseEdited,
        actorUid: uid,
        refId: expenseId,
        label: draft.title,
      );
    }
  }

  /// Soft delete: the tombstone and its revision stay so history remains
  /// explainable; balances exclude it.
  Future<void> softDelete({
    required String tourId,
    required Expense expense,
    required String uid,
  }) async {
    final ref = _col(tourId).doc(expense.id);
    await _db
        .runTransaction((tx) async {
          final snap = await tx.get(ref);
          if (!snap.exists) throw const AppException(AppErrorKind.notFound);
          final current = Expense.fromDoc(snap.id, snap.data()!);
          if (current.isDeleted) return;
          if (current.revisionCount != expense.revisionCount) {
            throw const AppException(AppErrorKind.conflict);
          }
          final revision = current.revisionCount + 1;
          tx.update(ref, {
            'deletedAt': FieldValue.serverTimestamp(),
            'deletedBy': uid,
            'revisionCount': revision,
            'updatedAt': FieldValue.serverTimestamp(),
            'updatedBy': uid,
          });
          tx.set(ref.collection('revisions').doc('$revision'), {
            'editorUid': uid,
            'editedAt': FieldValue.serverTimestamp(),
            'changedFields': ['deleted'],
            'before': {'deleted': false},
            'after': {'deleted': true},
          });
        })
        .timeout(const Duration(seconds: 20));
    await _feed.record(
      tourId,
      type: FeedEventType.expenseDeleted,
      actorUid: uid,
      refId: expense.id,
      label: expense.title,
    );
  }

  Future<List<Revision>> fetchRevisions(String tourId, String expenseId) async {
    final snap = await _col(tourId)
        .doc(expenseId)
        .collection('revisions')
        .orderBy('editedAt', descending: true)
        .limit(Revision.maxRevisions)
        .get();
    return snap.docs.map((d) => Revision.fromDoc(d.id, d.data())).toList();
  }

  /// Only changed fields, with Firestore-friendly values. No coordinates or
  /// credentials ever pass through here.
  static Map<String, Object?> _compact(
    Map<String, Object?> values,
    List<String> fields,
  ) => {
    for (final f in fields)
      f: switch (values[f]) {
        final DateTime d => Timestamp.fromDate(d.toUtc()),
        final other => other,
      },
  };
}

final expenseRepositoryProvider = Provider<ExpenseRepository>(
  (ref) => ExpenseRepository(
    ref.watch(firestoreProvider),
    ref.watch(feedRepositoryProvider),
  ),
);

final expensesProvider = StreamProvider.autoDispose
    .family<Snapshot<Expense>, String>(
      (ref, tourId) => ref.watch(expenseRepositoryProvider).watch(tourId),
    );

/// Balances are recomputed only when expenses or settlements change, never
/// on unrelated rebuilds.
final balancesProvider = Provider.autoDispose.family<TourBalances?, String>((
  ref,
  tourId,
) {
  final expenses = ref.watch(expensesProvider(tourId)).value;
  final settlements = ref.watch(settlementsProvider(tourId)).value;
  if (expenses == null || settlements == null) return null;
  // Unsynced expenses (offline adds) are listed as "Pending sync" but not
  // counted until the server has them.
  return computeBalances(
    expenses.items.where((e) => !e.hasPendingWrites),
    settlements.items,
  );
});
